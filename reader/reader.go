// Package reader parses Office Open XML spreadsheets (.xlsx, .xlsm, .xltx)
// into a model.Workbook. Parts the model does not cover (pivot caches,
// custom XML, VBA, external links, chart sheets) are preserved as raw
// parts so that saving a read workbook keeps them.
package reader

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"path"
	"strings"

	"github.com/gsoultan/gexcel/model"
	"github.com/gsoultan/gexcel/ooxml"
)

// Options tune parsing.
type Options struct {
	// MaxPartSize limits the decompressed size of any part (zip bomb
	// protection). Default 1 GiB.
	MaxPartSize int64
	// MaxCells limits the number of cells read per workbook; 0 = unlimited.
	MaxCells int
	// SkipDrawings leaves images and charts unread (faster for data-only use).
	SkipDrawings bool
	// Sheets restricts reading to the named sheets (others stay empty).
	Sheets []string
	// Strict makes malformed XML an error instead of best-effort parsing.
	Strict bool
}

// Errors.
var (
	ErrNotSpreadsheet = errors.New("reader: not a SpreadsheetML package")
	ErrEncrypted      = errors.New("reader: workbook is encrypted (CFB/OLE container); decryption is not supported yet")
	ErrLimit          = errors.New("reader: limit exceeded")
)

// Read parses a package from a ReaderAt.
func Read(r io.ReaderAt, size int64, opts ...Options) (*model.Workbook, error) {
	var o Options
	if len(opts) > 0 {
		o = opts[0]
	}
	if o.MaxPartSize == 0 {
		o.MaxPartSize = 1 << 30
	}
	var head [8]byte
	if n, _ := r.ReadAt(head[:], 0); n >= 8 && bytes.Equal(head[:8], []byte{0xD0, 0xCF, 0x11, 0xE0, 0xA1, 0xB1, 0x1A, 0xE1}) {
		return nil, ErrEncrypted
	}
	pr, err := ooxml.Open(r, size)
	if err != nil {
		return nil, err
	}
	pr.MaxPartSize = o.MaxPartSize
	rd := &docReader{pr: pr, opts: o, wb: model.New()}
	if err := rd.read(); err != nil {
		return nil, err
	}
	return rd.wb, nil
}

// ReadBytes parses a package held in memory.
func ReadBytes(data []byte, opts ...Options) (*model.Workbook, error) {
	return Read(bytes.NewReader(data), int64(len(data)), opts...)
}

// ReadFile parses a file.
func ReadFile(name string, opts ...Options) (*model.Workbook, error) {
	f, err := os.Open(name)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		return nil, err
	}
	return Read(f, st.Size(), opts...)
}

type docReader struct {
	pr     *ooxml.Reader
	opts   Options
	wb     *model.Workbook
	sst    []model.Value
	wbPart string
	cells  int
	// part names already consumed, so Preserved does not duplicate them
	used map[string]bool
	// streaming: worksheet parts by sheet name, parsed later on demand
	skipSheets bool
	sheetParts map[string]string
}

func (d *docReader) read() error {
	d.used = map[string]bool{"[Content_Types].xml": true, "_rels/.rels": true}
	rootRels, _ := d.pr.Rels("")
	doc, ok := ooxml.FindRel(rootRels, ooxml.RelOfficeDocument)
	if !ok {
		return ErrNotSpreadsheet
	}
	d.wbPart = ooxml.Resolve("", doc.Target)
	ct := d.pr.ContentType(d.wbPart)
	if !strings.Contains(ct, "spreadsheetml") && !strings.Contains(ct, "ms-excel") {
		return fmt.Errorf("%w: main part is %s", ErrNotSpreadsheet, ct)
	}
	d.use(d.wbPart)
	wbRels, _ := d.pr.Rels(d.wbPart)
	d.use(ooxml.RelsName(d.wbPart))
	// Properties.
	if rel, ok := ooxml.FindRel(rootRels, ooxml.RelCoreProps); ok {
		d.readCoreProps(ooxml.Resolve("", rel.Target))
	}
	if rel, ok := ooxml.FindRel(rootRels, ooxml.RelExtProps); ok {
		d.readAppProps(ooxml.Resolve("", rel.Target))
	}
	if rel, ok := ooxml.FindRel(rootRels, ooxml.RelCustomProps); ok {
		d.readCustomProps(ooxml.Resolve("", rel.Target))
	}
	// Theme, styles, shared strings.
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelTheme); ok {
		d.readTheme(ooxml.Resolve(d.wbPart, rel.Target))
	}
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelStyles); ok {
		if err := d.readStyles(ooxml.Resolve(d.wbPart, rel.Target)); err != nil {
			return err
		}
	}
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelSharedStrings); ok {
		if err := d.readSharedStrings(ooxml.Resolve(d.wbPart, rel.Target)); err != nil {
			return err
		}
	}
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelVBA); ok {
		name := ooxml.Resolve(d.wbPart, rel.Target)
		if data, err := d.pr.Part(name); err == nil {
			d.wb.VBAProject = data
			d.use(name)
			d.use(ooxml.RelsName(name))
		}
	}
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelMetadata); ok {
		name := ooxml.Resolve(d.wbPart, rel.Target)
		if data, err := d.pr.Part(name); err == nil {
			d.wb.Metadata = data
			d.use(name)
		}
	}
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelPersons); ok {
		d.use(ooxml.Resolve(d.wbPart, rel.Target))
	}
	if rel, ok := ooxml.FindRel(wbRels, ooxml.RelCalcChain); ok {
		d.use(ooxml.Resolve(d.wbPart, rel.Target)) // regenerated by Excel
	}
	// Workbook: sheets, names, settings.
	if err := d.readWorkbook(wbRels); err != nil {
		return err
	}
	// External links, pivot caches, rich data, other preserved parts.
	for _, rel := range wbRels {
		name := ooxml.Resolve(d.wbPart, rel.Target)
		switch rel.Type {
		case ooxml.RelExternalLink:
			raw := d.rawPart(name)
			if raw != nil {
				d.wb.ExternalLinks = append(d.wb.ExternalLinks, externalLinkOf(raw))
			}
		case ooxml.RelRichValue:
			if raw := d.rawPart(name); raw != nil {
				d.wb.RichData = append(d.wb.RichData, raw)
			}
		case ooxml.RelWorksheet, ooxml.RelChartsheet, ooxml.RelDialogsheet, ooxml.RelMacrosheet, ooxml.RelStyles, ooxml.RelTheme,
			ooxml.RelSharedStrings, ooxml.RelVBA, ooxml.RelMetadata, ooxml.RelPersons, ooxml.RelCalcChain, ooxml.RelPivotCacheDef:
		default:
			if rel.TargetMode == "External" {
				continue
			}
			if raw := d.rawPart(name); raw != nil {
				d.wb.Preserved = append(d.wb.Preserved, raw)
			}
		}
	}
	return nil
}

func (d *docReader) use(name string) { d.used[name] = true }

// rawPart loads a part and everything it relates to as a RawPart tree.
func (d *docReader) rawPart(name string) *model.RawPart {
	if d.used[name] {
		return nil
	}
	data, err := d.pr.Part(name)
	if err != nil {
		return nil
	}
	d.use(name)
	raw := &model.RawPart{Name: name, ContentType: d.pr.ContentType(name), Data: data}
	rels, _ := d.pr.Rels(name)
	d.use(ooxml.RelsName(name))
	for _, r := range rels {
		raw.Rels = append(raw.Rels, model.Relationship{ID: r.ID, Type: r.Type, Target: r.Target, TargetMode: r.TargetMode})
		if r.TargetMode == "External" {
			continue
		}
		target := ooxml.Resolve(name, r.Target)
		if sub := d.rawPart(target); sub != nil {
			if raw.Related == nil {
				raw.Related = map[string]*model.RawPart{}
			}
			raw.Related[target] = sub
		}
	}
	return raw
}

func externalLinkOf(raw *model.RawPart) *model.ExternalLink {
	el := &model.ExternalLink{Raw: raw}
	for _, r := range raw.Rels {
		if r.Type == ooxml.RelExternalLinkPath {
			el.Target = r.Target
		}
	}
	if n, err := ooxml.ParseDOM(raw.Data); err == nil {
		for _, s := range n.Path("externalBook", "sheetNames").Each("sheetName") {
			el.SheetNames = append(el.SheetNames, s.Attr("val"))
		}
	}
	return el
}

func (d *docReader) dom(name string) (*ooxml.Node, error) {
	data, err := d.pr.Part(name)
	if err != nil {
		return nil, err
	}
	n, err := ooxml.ParseDOM(data)
	if err != nil && d.opts.Strict {
		return nil, fmt.Errorf("reader: %s: %w", name, err)
	}
	return n, nil
}

func (d *docReader) wantSheet(name string) bool {
	if len(d.opts.Sheets) == 0 {
		return true
	}
	for _, s := range d.opts.Sheets {
		if strings.EqualFold(s, name) {
			return true
		}
	}
	return false
}

func partDir(name string) string {
	dir := path.Dir(name)
	if dir == "." {
		return ""
	}
	return dir
}

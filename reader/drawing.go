// readDrawing parses pictures, charts and shapes of a drawing part.
func (d *docReader) readDrawing(sh *model.Sheet, part string) {
	data, err := d.pr.Part(part)
	if err != nil {
		return
	}
	d.use(part)
	rels, _ := d.pr.Rels(part)
	d.use(ooxml.RelsName(part))
	root, err := ooxml.ParseDOM(data)
	if err != nil || root == nil {
		return
	}
	for _, anchorNode := range root.Children {
		var anchor model.Anchor
		switch anchorNode.Name {
		case "twoCellAnchor":
			anchor.Kind = model.AnchorTwoCell
			anchor.From = parseMarker(anchorNode.Child("from"))
			anchor.To = parseMarker(anchorNode.Child("to"))
			anchor.EditAs = anchorNode.Attr("editAs")
		case "oneCellAnchor":
			anchor.Kind = model.AnchorOneCell
			anchor.From = parseMarker(anchorNode.Child("from"))
			if e := anchorNode.Child("ext"); e != nil {
				anchor.Width, _ = strconv.ParseInt(e.Attr("cx"), 10, 64)
				anchor.Height, _ = strconv.ParseInt(e.Attr("cy"), 10, 64)
			}
		case "absoluteAnchor":
			anchor.Kind = model.AnchorAbsolute
			if p := anchorNode.Child("pos"); p != nil {
				anchor.X, _ = strconv.ParseInt(p.Attr("x"), 10, 64)
				anchor.Y, _ = strconv.ParseInt(p.Attr("y"), 10, 64)
			}
			if e := anchorNode.Child("ext"); e != nil {
				anchor.Width, _ = strconv.ParseInt(e.Attr("cx"), 10, 64)
				anchor.Height, _ = strconv.ParseInt(e.Attr("cy"), 10, 64)
			}
		default:
			continue
		}
		if pic := anchorNode.Child("pic"); pic != nil {
			img := &model.Image{Anchor: anchor}
			if pr := pic.Path("nvPicPr", "cNvPr"); pr != nil {
				img.Name = pr.Attr("name")
				img.Description = pr.Attr("descr")
				img.ID = ooxml.ParseInt(pr.Attr("id"), 0)
				if hl := pr.Child("hlinkClick"); hl != nil {
					if rel, ok := ooxml.RelByID(rels, relAttr(hl, "id")); ok {
						img.Hyperlink = rel.Target
					}
				}
			}
			if pl := pic.Path("nvPicPr", "cNvPicPr", "picLocks"); pl != nil {
				img.LockAspect = ooxml.ParseBool(pl.Attr("noChangeAspect"))
			}
			if blip := pic.Path("blipFill", "blip"); blip != nil {
				if rel, ok := ooxml.RelByID(rels, relAttr(blip, "embed")); ok {
					media := ooxml.Resolve(part, rel.Target)
					if data, err := d.pr.Part(media); err == nil {
						img.Data = data
						img.Format = strings.ToLower(strings.TrimPrefix(path.Ext(media), "."))
						if img.Format == "jpg" {
							img.Format = "jpeg"
						}
						d.use(media)
					}
				}
			}
			if xf := pic.Path("spPr", "xfrm"); xf != nil && anchor.Kind == model.AnchorTwoCell {
				if e := xf.Child("ext"); e != nil {
					img.Anchor.Width, _ = strconv.ParseInt(e.Attr("cx"), 10, 64)
					img.Anchor.Height, _ = strconv.ParseInt(e.Attr("cy"), 10, 64)
				}
			}
			if len(img.Data) > 0 {
				sh.Images = append(sh.Images, img)
			}
			continue
		}
		if gf := anchorNode.Child("graphicFrame"); gf != nil {
			if c := gf.Path("graphic", "graphicData", "chart"); c != nil {
				if rel, ok := ooxml.RelByID(rels, relAttr(c, "id")); ok {
					chartPart := ooxml.Resolve(part, rel.Target)
					if data, err := d.pr.Part(chartPart); err == nil {
						d.use(chartPart)
						d.use(ooxml.RelsName(chartPart))
						// Chart style/color parts are regenerated by Excel.
						crels, _ := d.pr.Rels(chartPart)
						for _, cr := range crels {
							d.use(ooxml.Resolve(chartPart, cr.Target))
						}
						ch := parseChart(data)
						if ch == nil {
							ch = &chart.Chart{Raw: data}
						}
						if pr := gf.Path("nvGraphicFramePr", "cNvPr"); pr != nil {
							ch.Name = pr.Attr("name")
						}
						ch.Anchor = chart.AnchorRef{FromRow: anchor.From.Row, FromCol: anchor.From.Col, FromRowOff: anchor.From.RowOff, FromColOff: anchor.From.ColOff,
							ToRow: anchor.To.Row, ToCol: anchor.To.Col, ToRowOff: anchor.To.RowOff, ToColOff: anchor.To.ColOff, OneCell: anchor.Kind != model.AnchorTwoCell}
						ch.Width, ch.Height = anchor.Width, anchor.Height
						sh.Charts = append(sh.Charts, ch)
					}
				}
			}
			continue
		}
		if sp := anchorNode.Child("sp"); sp != nil {
			shape := &model.Shape{Anchor: anchor}
			if pr := sp.Path("nvSpPr", "cNvPr"); pr != nil {
				shape.Name = pr.Attr("name")
			}
			if g := sp.Path("spPr", "prstGeom"); g != nil {
				shape.Preset = g.Attr("prst")
			}
			if f := sp.Path("spPr", "solidFill", "srgbClr"); f != nil {
				shape.Fill = style.RGB(f.Attr("val"))
			}
			if l := sp.Path("spPr", "ln", "solidFill", "srgbClr"); l != nil {
				shape.Line = style.RGB(l.Attr("val"))
			}
			if tb := sp.Child("txBody"); tb != nil {
				var lines []string
				for _, p := range tb.Each("p") {
					var sb strings.Builder
					for _, r := range p.Each("r") {
						if t := r.Child("t"); t != nil {
							sb.WriteString(t.Text)
						}
					}
					lines = append(lines, sb.String())
				}
				shape.Text = strings.Join(lines, "\n")
			}
			// Keep the raw anchor so unsupported shape details survive.
			var b ooxml.Builder
			writeNode(&b, anchorNode)
			shape.Raw = b.Bytes()
			sh.Shapes = append(sh.Shapes, shape)
		}
	}
}

func relAttr(n *ooxml.Node, name string) string {
	for _, a := range n.Attrs {
		if a.Name.Local == name {
			return a.Value
		}
	}
	return ""
}

func parseMarker(n *ooxml.Node) model.CellOffset {
	var c model.CellOffset
	if n == nil {
		return c
	}
	c.Col = ooxml.ParseInt(strings.TrimSpace(n.Child("col").Text), 0) + 1
	c.Row = ooxml.ParseInt(strings.TrimSpace(n.Child("row").Text), 0) + 1
	c.ColOff, _ = strconv.ParseInt(strings.TrimSpace(nodeText(n.Child("colOff"))), 10, 64)
	c.RowOff, _ = strconv.ParseInt(strings.TrimSpace(nodeText(n.Child("rowOff"))), 10, 64)
	return c
}

func nodeText(n *ooxml.Node) string {
	if n == nil {
		return ""
	}
	return n.Text
}
